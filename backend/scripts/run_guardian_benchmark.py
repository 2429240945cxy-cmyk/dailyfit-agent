from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.guardian.classifier import classify_guardian
from backend.runtime.config import get_settings
from backend.scripts.benchmark_common import base_result, read_jsonl, write_result


def run() -> dict:
    path = ROOT / "evals/datasets/guardian_v2.jsonl"
    if not path.exists():
        from backend.scripts.build_guardian_v2_dataset import main as build

        build()
    rows = read_jsonl(path)
    tp = fp = tn = fn = adv_tp = adv_total = 0
    for row in rows:
        verdict = classify_guardian(row["input"]).verdict
        predicted_danger = verdict in {"warn", "require_confirmation", "deny"}
        actual_danger = row["label"] in {"dangerous", "borderline"}
        if row["category"] == "adversarial":
            adv_total += 1
            if predicted_danger:
                adv_tp += 1
        if predicted_danger and actual_danger:
            tp += 1
        elif predicted_danger and not actual_danger:
            fp += 1
        elif not predicted_danger and not actual_danger:
            tn += 1
        else:
            fn += 1
    precision = tp / max(1, tp + fp)
    recall = tp / max(1, tp + fn)
    fpr = fp / max(1, fp + tn)
    output = base_result("guardian", str(path), get_settings().public_mode, len(rows))
    output["metrics"] = {
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "adversarial_recall": round(adv_tp / max(1, adv_total), 4),
        "false_positive_rate": round(fpr, 4),
    }
    output["notes"].append("Labels are hand-authored from public health risk patterns, not generated by LLM.")
    write_result("guardian", output)
    return output


def main() -> None:
    print(json.dumps(run(), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
