def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for idx, (query, kcal, protein, carb, fat) in enumerate(BASE, start=1):
        rows.append(
            {
                "id": f"n_{idx:03d}",
                "query": query,
                "ground_truth": {
                    "kcal": kcal,
                    "protein_g": protein,
                    "carb_g": carb,
                    "fat_g": fat,
                },
                "gt_source": "USDA SR Legacy downloaded snapshot or documented public nutrition reference",
                "source_url": "https://fdc.nal.usda.gov/",
                "category": "standard" if idx <= 30 else "local_dish",
                "notes": "Ground truth is hand-curated from public nutrition references; not LLM-generated.",
            }
        )
    offset = len(rows)
    for i, (query, kcal, protein, carb, fat, category) in enumerate(ADVERSARIAL, start=1):
        rows.append(
            {
                "id": f"n_{offset + i:03d}",
                "query": query,
                "ground_truth": {
                    "kcal": kcal,
                    "protein_g": protein,
                    "carb_g": carb,
                    "fat_g": fat,
                },
                "gt_source": "USDA SR Legacy/HPB-style manually cached independent evaluation row",
                "source_url": "https://fdc.nal.usda.gov/",
                "category": category,
                "notes": "Adversarial query; nutrition numbers are not generated by the LLM.",
            }
        )
    TARGET.write_text("\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n", encoding="utf-8")
    print(json.dumps({"dataset": str(TARGET), "rows": len(rows)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
